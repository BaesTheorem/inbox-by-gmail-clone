// Optional OAuth client baked into the APK. With it, the setup wizard offers a
// one-tap "sign in" path; without it, the wizard walks the user through making
// their own Google Cloud project. Never committed: see client.properties.example.
val clientProps = Properties().apply {
    val f = rootProject.file("client.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

// Release signing. Without keystore.properties the release build falls back to
// the debug key, which still installs but changes fingerprint per machine.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

